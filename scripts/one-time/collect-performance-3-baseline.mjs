#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUTPUT_DIR = path.join(ROOT, "local", "final-acceptance-evidence", "performance-3");

function parseArgs(argv) {
  const options = {
    baseUrl: process.env.PERF3_BASE_URL ?? "http://127.0.0.1:3000",
    cookie: process.env.PERF3_COOKIE ?? "",
    label: "warm",
    runs: 5,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--base-url") options.baseUrl = argv[++index];
    else if (token === "--cookie") options.cookie = argv[++index];
    else if (token === "--label") options.label = argv[++index];
    else if (token === "--runs") options.runs = Number(argv[++index]);
  }

  return options;
}

function percentile(values, ratio) {
  if (!values.length) return 0;
  const sorted = [...values].sort((left, right) => left - right);
  const index = Math.min(sorted.length - 1, Math.max(0, Math.ceil(sorted.length * ratio) - 1));
  return sorted[index];
}

function summarize(samples) {
  const durations = samples.map((sample) => sample.durationMs);
  const bytes = samples.map((sample) => sample.responseBytes);
  return {
    count: samples.length,
    durationMs: {
      p50: percentile(durations, 0.5),
      p95: percentile(durations, 0.95),
    },
    responseBytes: {
      p50: percentile(bytes, 0.5),
      p95: percentile(bytes, 0.95),
    },
  };
}

function isUuid(value) {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(value ?? "").trim());
}

async function measureRequest(baseUrl, cookie, scenario) {
  const startedAt = performance.now();
  const response = await fetch(`${baseUrl}${scenario.path}`, {
    method: scenario.method ?? "GET",
    headers: {
      ...(cookie ? { cookie } : {}),
      ...(scenario.body ? { "Content-Type": "application/json" } : {}),
    },
    body: scenario.body ? JSON.stringify(scenario.body) : undefined,
  });
  const buffer = Buffer.from(await response.arrayBuffer());
  const durationMs = performance.now() - startedAt;
  const text = buffer.toString("utf8");
  let error = null;
  if (!response.ok) {
    error = text.slice(0, 300);
  }
  return {
    ok: response.ok,
    status: response.status,
    durationMs: Number(durationMs.toFixed(1)),
    responseBytes: buffer.byteLength,
    serverTiming: response.headers.get("server-timing"),
    contentType: response.headers.get("content-type"),
    ...(error ? { error } : {}),
  };
}

async function resolveArchiveVersionId(baseUrl, cookie) {
  const configured = String(process.env.PERF3_ARCHIVE_VERSION_ID ?? "").trim();
  if (isUuid(configured)) {
    return configured;
  }

  const response = await fetch(`${baseUrl}/api/workspace/archive-tree`, {
    headers: { cookie },
  });
  const body = await response.json().catch(() => ({}));
  if (!response.ok) {
    throw new Error(`Unable to list archive tree (${response.status}): ${JSON.stringify(body).slice(0, 300)}`);
  }

  const records = Array.isArray(body.records) ? body.records : [];
  const latest = records.find((row) => row.isLatest && isUuid(row.versionId));
  const any = records.find((row) => isUuid(row.versionId));
  const versionId = latest?.versionId ?? any?.versionId ?? "";
  if (!versionId) {
    throw new Error("No archive versionId found. Archive a submission first, or set PERF3_ARCHIVE_VERSION_ID.");
  }
  return versionId;
}

function buildScenarios(archiveVersionId) {
  return [
    {
      name: "commissioner-list",
      path: "/api/submissions?pageSize=25",
    },
    {
      name: "commissioner-analytics",
      path: "/api/submissions/analytics",
    },
    {
      name: "archive-branch-view",
      path: `/api/workspace/archive-tree/versions/${encodeURIComponent(archiveVersionId)}/view`,
    },
    {
      name: "commissioner-csv-export",
      method: "POST",
      path: "/api/exports/submissions.csv",
      body: {
        filters: {
          createdFrom: process.env.PERF3_CREATED_FROM ?? "",
          createdTo: process.env.PERF3_CREATED_TO ?? "",
          query: "",
        },
        types: {
          comments: true,
          objections: true,
          counterproposal: true,
        },
      },
    },
  ];
}

function renderSummaryMarkdown(label, aggregate) {
  const lines = [
    `# Performance-3 summary (${label})`,
    "",
    "| Scenario | Samples | API p50 (ms) | API p95 (ms) | Bytes p50 | Bytes p95 |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
  ];

  for (const [name, stats] of Object.entries(aggregate)) {
    lines.push(
      `| ${name} | ${stats.count} | ${stats.durationMs.p50} | ${stats.durationMs.p95} | ${stats.responseBytes.p50} | ${stats.responseBytes.p95} |`,
    );
  }

  lines.push("", "_Generated by `scripts/one-time/collect-performance-3-baseline.mjs`_");
  return `${lines.join("\n")}\n`;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (!options.cookie) {
    console.error("PERF3_COOKIE or --cookie is required for authenticated scenarios.");
    process.exitCode = 1;
    return;
  }

  const archiveVersionId = await resolveArchiveVersionId(options.baseUrl, options.cookie);
  console.log(`Using archive version ${archiveVersionId}`);
  const scenarios = buildScenarios(archiveVersionId);
  const timestamp = new Date().toISOString().replaceAll(":", "").replace(/\..+/, "");
  const runDir = path.join(OUTPUT_DIR, "runs");
  const summaryDir = path.join(OUTPUT_DIR, "summary");
  fs.mkdirSync(runDir, { recursive: true });
  fs.mkdirSync(summaryDir, { recursive: true });

  const aggregate = Object.fromEntries(scenarios.map((scenario) => [scenario.name, []]));
  const runPayload = {
    collectedAt: new Date().toISOString(),
    label: options.label,
    baseUrl: options.baseUrl,
    archiveVersionId,
    runs: options.runs,
    scenarios: {},
  };

  for (const scenario of scenarios) {
    const samples = [];
    for (let index = 0; index < options.runs; index += 1) {
      const sample = await measureRequest(options.baseUrl, options.cookie, scenario);
      samples.push(sample);
      if (!sample.ok) {
        console.warn(`${scenario.name} run ${index + 1} failed with status ${sample.status}`);
      }
    }
    aggregate[scenario.name] = summarize(samples);
    runPayload.scenarios[scenario.name] = samples;
  }

  const runPath = path.join(runDir, `${timestamp}-${options.label}.json`);
  fs.writeFileSync(runPath, `${JSON.stringify(runPayload, null, 2)}\n`);
  fs.writeFileSync(
    path.join(summaryDir, `${options.label}.md`),
    renderSummaryMarkdown(options.label, aggregate),
  );

  console.log(`Wrote ${runPath}`);
  console.log(`Wrote ${path.join(summaryDir, `${options.label}.md`)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
