#!/usr/bin/env python3
"""Generate FED and place label GeoJSON for map-mvp Step 4.

Data sources (priority order for place names):
  1. Local bundle CSVs under scripts/data/bundle/ (schema-aligned paths)
     - profile_2021/006_dissemination_areas/territories_geo_index.csv
     - profile_2021/016_028_province_csds/*_geo_index.csv
     - profile_2021/raw/**/**_English_CSV_data.csv  (GEO_NAME + DGUID)
  2. Coordinate reference: scripts/data/yukon_places.json (read-only, not overwritten)
  3. DA centroids from map-mvp/data/single_fed_das.geojson (for profile CSV join)

FED names: scripts/data/fed_names_2023.json (read-only, not overwritten).

Does NOT call external APIs. Re-run after dropping CSVs into scripts/data/bundle/.
"""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "map-mvp" / "data"
CACHE_DIR = Path(__file__).resolve().parent / "data"
BUNDLE_DIR = CACHE_DIR / "bundle"

FED_GEOJSON = DATA_DIR / "fed_boundaries_2023.geojson"
DA_GEOJSON = DATA_DIR / "single_fed_das.geojson"
FED_NAMES_REF = CACHE_DIR / "fed_names_2023.json"
YUKON_PLACES_REF = CACHE_DIR / "yukon_places.json"

FED_LABELS_OUT = DATA_DIR / "fed_labels.geojson"
PLACE_LABELS_YT_OUT = DATA_DIR / "place_labels_yt.geojson"
PLACE_LABELS_CSD_OUT = DATA_DIR / "place_labels_csd.geojson"

TERRITORIES_GEO_INDEX = (
    BUNDLE_DIR / "profile_2021" / "006_dissemination_areas" / "territories_geo_index.csv"
)
GEO_INDEX_GLOB = "profile_2021/016_028_province_csds/*_geo_index.csv"
PROFILE_CSV_GLOB = "profile_2021/raw/**/*_English_CSV_data.csv"


# ---------------------------------------------------------------------------
# Geometry helpers (pure Python — no geopandas)
# ---------------------------------------------------------------------------


def ring_centroid(ring: list[list[float]]) -> tuple[float, float]:
    if len(ring) < 3:
        lng = sum(p[0] for p in ring) / len(ring)
        lat = sum(p[1] for p in ring) / len(ring)
        return lng, lat

    area = 0.0
    cx = 0.0
    cy = 0.0
    for i, point in enumerate(ring):
        nxt = ring[(i + 1) % len(ring)]
        cross = point[0] * nxt[1] - nxt[0] * point[1]
        area += cross
        cx += (point[0] + nxt[0]) * cross
        cy += (point[1] + nxt[1]) * cross

    area *= 0.5
    if abs(area) < 1e-12:
        lng = sum(p[0] for p in ring) / len(ring)
        lat = sum(p[1] for p in ring) / len(ring)
        return lng, lat

    return cx / (6.0 * area), cy / (6.0 * area)


def polygon_centroid(coords: list) -> tuple[float, float]:
    if not coords:
        return 0.0, 0.0

    best_area = 0.0
    best_centroid = ring_centroid(coords[0])
    for ring in coords:
        xs = [p[0] for p in ring]
        ys = [p[1] for p in ring]
        area = abs((max(xs) - min(xs)) * (max(ys) - min(ys)))
        if area >= best_area:
            best_area = area
            best_centroid = ring_centroid(ring)
    return best_centroid


def geometry_centroid(geometry: dict) -> tuple[float, float]:
    geom_type = geometry["type"]
    coords = geometry["coordinates"]

    if geom_type == "Polygon":
        return polygon_centroid(coords)
    if geom_type == "MultiPolygon":
        largest = coords[0]
        largest_area = 0.0
        for polygon in coords:
            ring = polygon[0]
            xs = [p[0] for p in ring]
            ys = [p[1] for p in ring]
            area = abs((max(xs) - min(xs)) * (max(ys) - min(ys)))
            if area > largest_area:
                largest_area = area
                largest = polygon
        return polygon_centroid(largest)
    if geom_type == "Point":
        return coords[0], coords[1]
    return 0.0, 0.0


# ---------------------------------------------------------------------------
# Reference data (read-only)
# ---------------------------------------------------------------------------


def load_fed_names() -> dict[str, str]:
    if not FED_NAMES_REF.exists():
        raise SystemExit(
            f"Missing FED name reference: {FED_NAMES_REF}\n"
            "This file is maintained separately and is not regenerated by this script."
        )
    return json.loads(FED_NAMES_REF.read_text(encoding="utf-8"))


def load_yukon_coord_reference() -> tuple[dict[str, dict], dict[str, dict]]:
    """Index yukon_places.json by geo_code and lower-case name (read-only)."""
    by_code: dict[str, dict] = {}
    by_name: dict[str, dict] = {}

    if not YUKON_PLACES_REF.exists():
        return by_code, by_name

    for row in json.loads(YUKON_PLACES_REF.read_text(encoding="utf-8")):
        code = normalize_geo_code(row.get("geo_code", ""))
        name = str(row.get("name", "")).strip()
        if code:
            by_code[code] = row
        if name:
            by_name[name.lower()] = row

    return by_code, by_name


def normalize_geo_code(value: object) -> str:
    text = str(value).strip()
    if not text or text.lower() == "nan":
        return ""
    if "." in text:
        text = text.split(".", 1)[0]
    return text


