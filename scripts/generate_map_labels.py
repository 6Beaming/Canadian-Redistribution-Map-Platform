# StatCan / Elections Canada CSVs are often UTF-8 but may be cp1252 (French accents).
CSV_ENCODINGS = ("utf-8-sig", "utf-8", "cp1252", "latin-1")


def read_csv_dict_rows(path: Path) -> list[dict[str, str]]:
    raw = path.read_bytes()
    last_error: Exception | None = None
    for encoding in CSV_ENCODINGS:
        try:
            text = raw.decode(encoding)
            return list(csv.DictReader(io.StringIO(text)))
        except UnicodeDecodeError as error:
            last_error = error
    if last_error:
        raise last_error
    text = raw.decode(CSV_ENCODINGS[0])
    return list(csv.DictReader(text.splitlines()))


def read_geo_index_csv(path: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for row in read_csv_dict_rows(path):
        code = normalize_geo_code(
            row.get("Geo Code") or row.get("GEO_CODE") or row.get("geo_code") or ""
        )
        name = str(
            row.get("Geo Name") or row.get("GEO_NAME") or row.get("geo_name") or ""
        ).strip()
        if code and name:
            rows.append({"geo_code": code, "name": name})
    return rows


def discover_profile_csvs() -> list[Path]:
    base = BUNDLE_DIR / "profile_2021" / "raw"
    if not base.exists():
        return []
    return sorted(base.rglob("*_English_CSV_data.csv"))


def read_profile_geo_names(path: Path) -> dict[str, str]:
    """DGUID -> GEO_NAME from long-format profile CSV (one row per characteristic)."""
    names: dict[str, str] = {}
    for row in read_csv_dict_rows(path):
        char_id = str(row.get("CHARACTERISTIC_ID", "")).strip()
        if char_id and char_id != "1":
            continue
        dguid = str(row.get("DGUID", "")).strip()
        geo_name = str(row.get("GEO_NAME", "")).strip()
        if dguid and geo_name:
            names[dguid] = geo_name
    return names


def load_da_centroids() -> dict[str, tuple[float, float, str]]:
    """DGUID -> (lng, lat, label_hint) from single_fed_das.geojson."""
    if not DA_GEOJSON.exists():
        return {}

    geojson = json.loads(DA_GEOJSON.read_text(encoding="utf-8"))
    centroids: dict[str, tuple[float, float, str]] = {}
    for feature in geojson.get("features", []):
        dguid = str(feature.get("properties", {}).get("DGUID", "")).strip()
        if not dguid:
            continue
        lng, lat = geometry_centroid(feature["geometry"])
        centroids[dguid] = (lng, lat, dguid)
    return centroids


def resolve_coord(
    geo_code: str,
    name: str,
    by_code: dict[str, dict],
    by_name: dict[str, dict],
) -> tuple[float, float] | None:
    code = normalize_geo_code(geo_code)
    if code and code in by_code:
        row = by_code[code]
        return row["lng"], row["lat"]

    key = name.lower()
    if key in by_name:
        row = by_name[key]
        return row["lng"], row["lat"]

    return None


def place_feature(
    name: str,
    lng: float,
    lat: float,
    geo_code: str = "",
    source: str = "",
) -> dict:
    props: dict[str, str] = {"name": name}
    if geo_code:
        props["geo_code"] = geo_code
    if source:
        props["source"] = source
    return {
        "type": "Feature",
        "geometry": {"type": "Point", "coordinates": [lng, lat]},
        "properties": props,
    }


def dedupe_features(features: list[dict]) -> list[dict]:
    seen: set[str] = set()
    out: list[dict] = []
    for feature in features:
        name = feature["properties"]["name"].lower()
        if name in seen:
            continue
        seen.add(name)
        out.append(feature)
    out.sort(key=lambda f: f["properties"]["name"])
    return out


# ---------------------------------------------------------------------------
# Label builders
# ---------------------------------------------------------------------------


def build_fed_labels() -> dict:
    fed_geojson = json.loads(FED_GEOJSON.read_text(encoding="utf-8"))
    fed_names = load_fed_names()
    features = []

    for feature in fed_geojson.get("features", []):
        fed_num = str(feature.get("properties", {}).get("fed_num", "")).strip()
        if not fed_num:
            continue
        lng, lat = geometry_centroid(feature["geometry"])
        features.append(
            place_feature(
                fed_names.get(fed_num, f"FED {fed_num}"),
                lng,
                lat,
                geo_code=fed_num,
                source="fed_boundaries_2023.geojson+fed_names_2023.json",
            )
        )

    features.sort(key=lambda f: f["properties"]["geo_code"])
    return {"type": "FeatureCollection", "features": features}


def build_place_labels_yt() -> tuple[dict, list[str]]:
    """Yukon / territories place labels for map-mvp."""
    log: list[str] = []
    features: list[dict] = []
    by_code, by_name = load_yukon_coord_reference()

    if TERRITORIES_GEO_INDEX.exists():
        rows = read_geo_index_csv(TERRITORIES_GEO_INDEX)
        log.append(f"Read {len(rows)} rows from {TERRITORIES_GEO_INDEX.name}")
        for row in rows:
            coord = resolve_coord(row["geo_code"], row["name"], by_code, by_name)
            if coord:
                lng, lat = coord
                features.append(
                    place_feature(
                        row["name"],
                        lng,
                        lat,
                        geo_code=row["geo_code"],
                        source="territories_geo_index.csv",
                    )
                )
            else:
                log.append(f"  [skip] no coordinates for {row['name']} ({row['geo_code']})")

    profile_names: dict[str, str] = {}
    for csv_path in discover_profile_csvs():
        names = read_profile_geo_names(csv_path)
        profile_names.update(names)
        log.append(f"Read {len(names)} GEO_NAME rows from {csv_path.relative_to(BUNDLE_DIR)}")

    if profile_names:
        da_centroids = load_da_centroids()
        matched = 0
        for dguid, geo_name in profile_names.items():
            if dguid not in da_centroids:
                continue
            lng, lat, _ = da_centroids[dguid]
            features.append(
                place_feature(
                    geo_name,
                    lng,
                    lat,
                    geo_code=dguid,
                    source="profile_csv+single_fed_das.geojson",
                )
            )
            matched += 1
        log.append(f"Joined {matched} DA-level labels from profile CSV + DA centroids")

    if not features and YUKON_PLACES_REF.exists():
        log.append(f"Fallback: using coordinate reference {YUKON_PLACES_REF.name}")
        for row in json.loads(YUKON_PLACES_REF.read_text(encoding="utf-8")):
            features.append(
                place_feature(
                    row["name"],
                    row["lng"],
                    row["lat"],
                    geo_code=str(row.get("geo_code", "")),
                    source="yukon_places.json",
                )
            )

    features = dedupe_features(features)
    if not features:
        log.append(
            "No Yukon place labels produced. Add CSVs under scripts/data/bundle/ "
            "or ensure scripts/data/yukon_places.json exists."
        )

    return {"type": "FeatureCollection", "features": features}, log


def build_place_labels_csd() -> tuple[dict, list[str]]:
    """Province CSD name indexes from 016_028 (optional national layer)."""
    log: list[str] = []
    features: list[dict] = []
    by_code, by_name = load_yukon_coord_reference()

    for path in sorted(BUNDLE_DIR.glob(GEO_INDEX_GLOB)):
        prov = path.stem.replace("_geo_index", "")
        rows = read_geo_index_csv(path)
        log.append(f"Read {len(rows)} rows from {path.name}")
        for row in rows:
            coord = resolve_coord(row["geo_code"], row["name"], by_code, by_name)
            if not coord:
                continue
            lng, lat = coord
            features.append(
                place_feature(
                    row["name"],
                    lng,
                    lat,
                    geo_code=row["geo_code"],
                    source=f"016_028/{path.name}",
                )
            )
        if not features:
            log.append(
                f"  [note] {prov}: names only — no coordinates until CSD boundaries "
                "or a coord lookup table is added"
            )

    features = dedupe_features(features)
    return {"type": "FeatureCollection", "features": features}, log


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if not FED_GEOJSON.exists():
        raise SystemExit(f"Missing FED GeoJSON: {FED_GEOJSON}")

    print(f"Bundle CSV root: {BUNDLE_DIR}")
    print("Reference files (read-only):", FED_NAMES_REF.name, YUKON_PLACES_REF.name)
    print()

    fed_labels = build_fed_labels()
    place_yt, yt_log = build_place_labels_yt()
    place_csd, csd_log = build_place_labels_csd()

    FED_LABELS_OUT.write_text(json.dumps(fed_labels, ensure_ascii=False), encoding="utf-8")
    PLACE_LABELS_YT_OUT.write_text(json.dumps(place_yt, ensure_ascii=False), encoding="utf-8")
    if place_csd["features"]:
        PLACE_LABELS_CSD_OUT.write_text(
            json.dumps(place_csd, ensure_ascii=False), encoding="utf-8"
        )

    print(f"Wrote {len(fed_labels['features'])} FED labels -> {FED_LABELS_OUT}")
    print(f"Wrote {len(place_yt['features'])} Yukon place labels -> {PLACE_LABELS_YT_OUT}")
    if place_csd["features"]:
        print(f"Wrote {len(place_csd['features'])} CSD labels -> {PLACE_LABELS_CSD_OUT}")

    print("\n--- Yukon label pipeline ---")
    for line in yt_log:
        print(line)

    if csd_log:
        print("\n--- 016_028 CSD index ---")
        for line in csd_log:
            print(line)

    if not TERRITORIES_GEO_INDEX.exists():
        print(
            f"\nTip: drop territories_geo_index.csv at:\n  {TERRITORIES_GEO_INDEX}\n"
            "then re-run this script."
        )


if __name__ == "__main__":
    main()
